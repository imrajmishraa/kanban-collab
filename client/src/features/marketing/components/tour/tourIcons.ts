/** Twenty-five marks from the pool, starting at `start` and wrapping once. */
export function gridFrom(start: number): IconSvgElement[] {
  return Array.from(
    { length: 25 },
    (_, index) => TOUR_ICONS[(start + index) % TOUR_ICONS.length],
  );
}
